// gen-schema.mjs — turn the domain contract's schema into a TypeScript module, so every
// consumer (Metro, Vite, webpack, Node) loads the same thing and none has to read `.qsql`.
//
// Source: design/specs/domain/chat-sapp.qsql (the single source; edit that, never the output).
// Output: src/protocol/schema.generated.ts (gitignored; written on every build, test and typecheck).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../../design/specs/domain/chat-sapp.qsql');
const target = resolve(here, '../src/protocol/schema.generated.ts');

const qsql = readFileSync(source, 'utf8');
const out = `// GENERATED by scripts/gen-schema.mjs from design/specs/domain/chat-sapp.qsql. Do not edit.
/** The chat sApp schema, exactly as written in the domain contract. */
export const CHAT_SCHEMA_QSQL: string = ${JSON.stringify(qsql)};
`;
let current = '';
try { current = readFileSync(target, 'utf8'); } catch { /* first run */ }
if (current !== out) writeFileSync(target, out);
