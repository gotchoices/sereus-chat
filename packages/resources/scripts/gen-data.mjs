// Embeds the JSON data (strings/*.json, tokens/*.json) into src/data.generated.ts, so
// every consumer — Metro, Vite, Node, a CLI — imports plain JS with types, and nobody
// needs JSON-import support. The JSON files are the source; edit those.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => JSON.parse(readFileSync(join(root, path), 'utf8'));
const locales = readdirSync(join(root, 'strings')).filter(f => f.endsWith('.json')).map(f => f.slice(0, -5)).sort();
if (!locales.includes('en')) throw new Error('strings/en.json is required: it is the complete catalog');

const lines = [
  '// GENERATED by scripts/gen-data.mjs from strings/*.json and tokens/*.json. Do not edit.',
  `export const en = ${JSON.stringify(read('strings/en.json'), null, 2)} as const;`,
  '',
  '/** The full catalog\'s shape; other locales are partial and fall back to English. */',
  'export type Catalog = DeepStrings<typeof en>;',
  'type DeepStrings<T> = { [K in keyof T]: T[K] extends string ? string : DeepStrings<T[K]> };',
  'export type PartialCatalog = DeepPartial<Catalog>;',
  'type DeepPartial<T> = { [K in keyof T]?: T[K] extends string ? string : DeepPartial<T[K]> };',
  '',
  `export const locales = ${JSON.stringify(locales)} as const;`,
  'export type Locale = (typeof locales)[number];',
  '',
  'export const strings: { en: Catalog } & Record<Locale, PartialCatalog> = {',
  ...locales.map(l => `  ${JSON.stringify(l)}: ${l === 'en' ? 'en' : JSON.stringify(read(`strings/${l}.json`), null, 2).replace(/\n/g, '\n  ')},`),
  '};',
  '',
  `export const colors = ${JSON.stringify(read('tokens/colors.json'), null, 2)} as const;`,
  '',
  `export const layout = ${JSON.stringify(read('tokens/layout.json'), null, 2)} as const;`,
  '',
];
writeFileSync(join(root, 'src/data.generated.ts'), lines.join('\n'));
